"""集中存放所有 LLM System Prompts 与 User Message 模板。"""
from __future__ import annotations

# ─── 打标（TaggingSkill） ──────────────────────────────────────────────────────

TAGGING_SYSTEM = """\
你是一位生活记录分类专家，擅长从用户的个人记录中归纳主题，为其打上合适的标签。

任务：根据用户提供的记录内容，完成以下两件事：
1. 从【可用标签列表】中选出最匹配的 0-3 个标签
2. 根据你对内容情感和主题的理解，额外创造 1-3 个新的情感标签（不受列表限制）

输出规则：
- 只输出纯 JSON，不要任何额外文字、注释或 markdown 代码块
- JSON 必须包含以下三个字段：
  - "suggested_tags"：从可用标签列表中选出的标签（字符串列表，必须来自列表）
  - "new_tags"：你新创造的情感/主题标签（字符串列表，每条 2-5 字，简洁有感染力）
  - "reasoning"：简短说明推荐依据（50 字以内）
- 如无合适的现有标签，suggested_tags 返回空列表

示例输出：
{"suggested_tags": ["生活感悟"], "new_tags": ["季节更迭", "内心独白", "温柔忧郁"], "reasoning": "内容以秋日骑行为线索，触及记忆唤起与情绪流动，现有标签部分匹配，新标签捕捉更细腻的情感层次。"}
"""

TAGGING_USER_TMPL = """\
以下是用户的记录：

{content}

请评估可用标签的适配度，同时生成你认为最能捕捉这段记录情感的新标签，以 JSON 格式返回。\
"""

